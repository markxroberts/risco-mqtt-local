const assert = require('assert/strict');
const { fixture } = require('./helpers.cjs');
const tick = () => new Promise(resolve => setImmediate(resolve));
(async () => {
  const f = fixture({ arming_modes: { partition: { Garage: { armed_home: 'armed_group_B' } } } });
  f.init();
  const discovery = () => JSON.parse(f.last('/alarm_control_panel/risco-alarm-panel/3/config'));
  assert.equal(discovery().payload_arm_home, 'armed_group_B');
  assert.equal(discovery().supported_features.includes(null), false);
  f.message('republish', 'states');
  assert.equal(f.last('/alarm/partition/3/status'), 'armed_home', 'mapping works for non-contiguous IDs');
  assert.equal(f.last('/alarm/systemmessage'), 'AC fault', 'real message is not overwritten');
  f.message('republish', 'autodiscovery');
  f.message('republish', 'states');
  assert.equal(f.last('/alarm/partition/3/status'), 'armed_home');
  f.message('alarm/partition/1/set', 'armed_group_D'); await tick();
  assert.equal(f.calls.length, 0, 'not-ready group arm waits without falling through');
  f.panel.partitions.emit('PStatusChanged', 3, 'Ready'); await tick();
  assert.equal(f.calls.length, 0, 'another partition must not trigger queued arm');
  f.panel.partitions.byId(1).Ready = true;
  f.panel.partitions.emit('PStatusChanged', 1, 'Ready'); await tick();
  assert.deepEqual(f.calls, [['group', 1, 4]], 'group survives deferred arming');
  assert.equal([...f.timers.values()].some(t => t.delay === 30000), false);
  f.panel.partitions.byId(1).Ready = false;
  f.message('alarm/partition/1/set', 'armed_home'); await tick();
  f.runTimer(30000);
  f.panel.partitions.byId(1).Ready = true;
  f.panel.partitions.emit('PStatusChanged', 1, 'Ready'); await tick();
  assert.equal(f.calls.length, 1, 'expired request never arms');
  f.panel.failAway = true;
  f.message('alarm/partition/1/set', 'armed_away'); await tick();
  assert.deepEqual(f.calls.at(-1), ['away', 1], 'failed away command does not fall through to group arm');
  f.message('alarm/output/1/trigger', '1'); await tick();
  assert.equal(f.calls.filter(c => c[0] === 'output').length, 0, 'already-active output is not toggled off');
  f.message('alarm/zone/1-bypass/set', 'invalid'); await tick();
  assert.equal(f.calls.filter(c => c[0] === 'bypass').length, 0);
  f.panel.riscoComm.emit('CommsError', JSON.stringify({ name: 'RiscoCommandError', cmd: { commandStr: 'CLOCK' } }));
  f.message('republish', 'states');
  assert.equal(f.last('/alarm/proxystatus'), '0', 'republish cannot mark disconnected panel connected');
  const before = f.published.length;
  f.client.emit('close'); f.client.emit('reconnect');
  assert.equal(f.published.length, before, 'MQTT retry is not a successful connection');
  assert.equal(f.mqttOptions.username, null, 'anonymous credentials are not stringified');
  const other = fixture({ risco_mqtt_topic: 'test.panel' }); other.init();
  other.message('alarm/partition/3/set', 'armed_home'); await tick();
  assert.deepEqual(other.calls, [['home', 3]]);
  other.client.emit('message', 'testXpanel/alarm/partition/3/set', Buffer.from('disarmed')); await tick();
  assert.equal(other.calls.length, 1, 'topic metacharacters match literally');
  const pending = fixture(); pending.init();
  pending.message('alarm/partition/1/set', 'armed_home'); await tick();
  pending.message('alarm/partition/1/set', 'disarmed'); await tick();
  pending.panel.partitions.byId(1).Ready = true;
  pending.panel.partitions.emit('PStatusChanged', 1, 'Ready'); await tick();
  assert.deepEqual(pending.calls, [['disarm', 1]], 'disarm cancels pending arming');
  pending.panel.partitions.byId(1).Ready = false;
  pending.message('alarm/partition/1/set', 'armed_group_C'); await tick();
  pending.panel.riscoComm.tcpSocket.emit('Disconnected', true);
  pending.panel.partitions.byId(1).Ready = true;
  pending.panel.partitions.emit('PStatusChanged', 1, 'Ready'); await tick();
  assert.deepEqual(pending.calls, [['disarm', 1]], 'disconnect cancels pending arming');
  const defaults = fixture(); defaults.init();
  assert.equal(defaults.last('/alarm_control_panel/risco-alarm-panel/3/config') !== undefined, true);
  assert.equal(JSON.parse(defaults.last('/alarm_control_panel/risco-alarm-panel/3/config')).payload_arm_home, 'armed_home', 'instances do not mutate defaults');
  console.log('Behavior regression tests passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
